	function detect() {
		const nav = (root.navigator && (root.navigator.language || '')) || '';
		return nav.toLowerCase().indexOf('ko') === 0 ? 'ko' : 'en';
	}

	function t(lang, key, vars) {
		const table = STRINGS[lang] || STRINGS.en;
		let s = Object.prototype.hasOwnProperty.call(table, key) ? table[key]
			: (Object.prototype.hasOwnProperty.call(STRINGS.en, key) ? STRINGS.en[key] : key);
		if (vars) {
			s = s.replace(/\{(\w+)\}/g, function (m, k) {
				return Object.prototype.hasOwnProperty.call(vars, k) ? String(vars[k]) : m;
			});
		}
		return s;
	}

	const api = { STRINGS: STRINGS, detect: detect, t: t };
	if (typeof module === 'object' && module.exports) {
		module.exports = api;
	} else {
		root.KaiI18n = api;
	}
